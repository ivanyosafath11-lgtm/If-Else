public class ProgramaCalificacion {
    public static void main(String[] args) {
        // Variable que almacena la calificación del alumno
        int calificacion = 85;

        // Estructura condicional if-else
        if (calificacion >= 70) {
            System.out.println("Aprobado con buena calificación: " + calificacion);
        } else {
            System.out.println("Reprobado. Calificación: " + calificacion);
        }
    }
}